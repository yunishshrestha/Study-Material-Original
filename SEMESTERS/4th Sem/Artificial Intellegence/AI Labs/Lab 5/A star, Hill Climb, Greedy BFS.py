landscape = [2, 5, 8, 12, 10, 15, 11, 13, 9, 14]

print("HILL CLIMBING SEARCH (DYNAMIC)\n")

print("Index: ", *range(len(landscape)))
print("Value: ", *landscape)
print()

def hill_climb(start):
    current = start
    print(f"Start at Index {current}, Value {landscape[current]}")
    print("Climbing...")

    while True:
        if current > 0 and landscape[current - 1] > landscape[current]:
            current -= 1
            print(f"  Move left to {current}, Value {landscape[current]}")
        elif current < len(landscape) - 1 and landscape[current + 1] > landscape[current]:
            current += 1
            print(f"  Move right to {current}, Value {landscape[current]}")
        else:
            break

    print(f"\nPeak reached at Index {current}, Value {landscape[current]}")
    print("GLOBAL MAXIMUM FOUND!\n" if landscape[current] == max(landscape)
          else "LOCAL MAXIMUM (not the highest)\n")

for start in [5, 2, 7, 0]:
    hill_climb(start)

